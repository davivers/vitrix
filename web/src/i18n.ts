const dict: Record<Lang, Record<Key, string>> = { en, pt };
const KEY = "vitrix.lang";
const HTML_LANG: Record<Lang, string> = { en: "en", pt: "pt-BR" };
const LOCALE: Record<Lang, string> = { en: "en", pt: "pt-BR" };

const isLang = (v: unknown): v is Lang => v === "en" || v === "pt";

function initial(): Lang {
  try {
    const q = new URLSearchParams(location.search).get("lang"); // screenshots: ?lang=pt (validated against LANGS)
    if (isLang(q)) return q;
    const v = localStorage.getItem(KEY);
    if (isLang(v)) return v;
  } catch {
    /* storage unavailable */
  }
  return "en";
}

let current: Lang = initial();
if (typeof document !== "undefined") document.documentElement.lang = HTML_LANG[current];

export const getLang = () => current;
/** Locale for Intl / toLocale*String. */
export const locale = () => LOCALE[current];

/** Persist the language and reload: module-level labels and every t() call re-evaluate in the new language. */
export function setLang(lang: Lang) {
  if (lang === current) return;
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    /* applies for this page view only (via ?lang=) */
  }
  const url = new URL(location.href);
  url.searchParams.set("lang", lang); // survives a blocked localStorage; validated against LANGS on load
  location.replace(url.toString());
}

/** Translate a key; `{name}` placeholders are filled from `vars`. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const text = dict[current][key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : text;
}

/** "1 rule" / "3 rules": keys `<base>_one` and `<base>_other` with a {n} placeholder. */
export function tn(base: string, n: number): string {
  return t((n === 1 ? `${base}_one` : `${base}_other`) as Key, { n });
}

/** Current language and the setter (which reloads the page). */
export function useLang(): [Lang, (l: Lang) => void] {
  return [current, setLang];
}
