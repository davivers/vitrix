"""Content packs: import community Sigma rules (SigmaHQ) with starter test cases.

    vitrix pack add sigmahq --product windows --category process_creation --limit 20

Sources: `sigmahq` (the SigmaHQ repository archive, downloaded from GitHub), a local clone or
folder of Sigma rules, or a local .zip. Only `rules/` of the archive is read, in memory; nothing
is executed. Each rule goes to `rules/<into>/<path inside rules/>` and gets a cases file built
from its own selections:

- **positive**: an event that satisfies the selections (values derived from the modifiers);
- **negative**: the same fields with benign values;
- **false positive**: the positive event plus the fields of an exclusion (`filter_*`), proving it.

Every generated case is checked with the local evaluator before it is written: a rule whose
cases cannot be generated (regex, unsupported modifiers, correlation) is skipped unless
`include_untested` is set. Generated cases are a starting point: replace them with real events.
"""

from __future__ import annotations

import io
import urllib.request
import zipfile
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

import yaml

from .config import Config
from .evaluator import UnsupportedError, _selections, check_supported, evaluate, exclusion_selections

SIGMAHQ_URL = "https://github.com/SigmaHQ/sigma/archive/refs/heads/master.zip"
_ALLOWED_PREFIXES = ("https://github.com/", "https://codeload.github.com/")
MAX_DOWNLOAD = 200 * 1024 * 1024
BENIGN = "vitrix-benign-value"
HEADER = "# Generated by `vitrix pack add` from the rule's own selections: replace with real events.\n"


class PackError(Exception):
    pass


@dataclass
class PackResult:
    imported: list[dict] = field(default_factory=list)  # {id, title, cases, state}
    skipped: list[dict] = field(default_factory=list)  # {path, reason}
    matched: int = 0  # rules that passed the filters


# --------------------------------------------------------------------------- reading the source


def _download(url: str) -> bytes:
    if not url.startswith(_ALLOWED_PREFIXES):
        raise PackError("only GitHub archive URLs (https://github.com/...) are accepted")
    req = urllib.request.Request(url, headers={"User-Agent": "vitrix"})
    try:
        # URL checked above (https GitHub only); the redirect target is checked below
        with urllib.request.urlopen(req, timeout=120) as res:  # nosec B310
            if not res.geturl().startswith(_ALLOWED_PREFIXES):
                raise PackError(f"redirected outside GitHub: {res.geturl()[:80]}")
            data = res.read(MAX_DOWNLOAD + 1)
    except OSError as exc:
        raise PackError(f"could not download {url}: {exc}") from exc
    if len(data) > MAX_DOWNLOAD:
        raise PackError("archive larger than 200 MB")
    return data


def _from_zip(data: bytes, folder: str) -> dict[str, str]:
    """{path inside <folder>/: text} of every .yml in the archive."""
    out: dict[str, str] = {}
    with zipfile.ZipFile(io.BytesIO(data)) as zf:
        for info in zf.infolist():
            if info.is_dir() or not info.filename.endswith((".yml", ".yaml")) or info.file_size > 1_000_000:
                continue
            parts = PurePosixPath(info.filename).parts
            # archives from GitHub have one top folder (sigma-master/rules/...)
            for i in range(min(2, len(parts))):
                if parts[i] == folder:
                    rel = PurePosixPath(*parts[i + 1:])
                    if ".." not in rel.parts:
                        out[rel.as_posix()] = zf.read(info).decode("utf-8", "replace")
                    break
    return out


def _from_dir(root: Path, folder: str) -> dict[str, str]:
    base = root / folder if (root / folder).is_dir() else root
    return {p.relative_to(base).as_posix(): p.read_text(encoding="utf-8", errors="replace")
            for p in sorted(base.rglob("*")) if p.suffix in (".yml", ".yaml") and p.is_file()}


def read_source(source: str, folder: str = "rules") -> dict[str, str]:
    if source == "sigmahq":
        return _from_zip(_download(SIGMAHQ_URL), folder)
    if source.startswith("https://"):
        return _from_zip(_download(source), folder)
    path = Path(source)
    if path.is_dir():
        return _from_dir(path, folder)
    if path.is_file() and zipfile.is_zipfile(path):
        return _from_zip(path.read_bytes(), folder)
    raise PackError(f"source not found: {source} (use sigmahq, a folder of Sigma rules, a .zip or a GitHub archive URL)")


# --------------------------------------------------------------------------- generated cases


def _fill(value: str) -> str:
    """A concrete string for a Sigma value with wildcards (* and ? become letters)."""
    out, i = [], 0
    while i < len(value):
        ch = value[i]
        if ch == "\\" and i + 1 < len(value) and value[i + 1] in "*?\\":
            out.append(value[i + 1])
            i += 2
            continue
        out.append("x" if ch in "*?" else ch)
        i += 1
    return "".join(out)


def _value(mods: set[str], values: list) -> object:
    """A value that satisfies field|mods: values. Raises UnsupportedError when it cannot."""
    if "exists" in mods:
        return "x" if values and values[0] else None
    if "re" in mods:
        raise UnsupportedError("regular expressions")
    vals = [v for v in values if v is not None]
    if not vals:
        return None
    if isinstance(vals[0], (int, float)) and not isinstance(vals[0], bool) and not mods - {"cased"}:
        return vals[0]
    filled = [_fill(str(v)) for v in (vals if "all" in mods else vals[:1])]
    if "all" in mods and len(filled) > 1 and "contains" not in mods:
        raise UnsupportedError("|all without contains")
    body = " ".join(filled)
    if "contains" in mods:
        return f"a {body} b"
    if "startswith" in mods:
        return f"{body} b"
    if "endswith" in mods:
        return f"a {body}" if not body.startswith(("\\", "/", ".")) else f"a{body}"
    return body


def _event_for(selection: object) -> dict:
    if isinstance(selection, list):
        dicts = [x for x in selection if isinstance(x, dict)]
        if dicts:
            return _event_for(dicts[0])
        if selection:
            return {"Message": f"a {_fill(str(selection[0]))} b"}
        raise UnsupportedError("empty selection")
    if not isinstance(selection, dict):
        raise UnsupportedError("selection format")
    event: dict = {}
    for spec, raw in selection.items():
        name, *mods = str(spec).split("|")
        value = _value(set(mods), raw if isinstance(raw, list) else [raw])
        if value is not None:
            event[name] = value
    return event


def generate_cases(doc: dict) -> list[dict]:
    """Positive, negative and (when there is an exclusion) false-positive cases, all verified."""
    check_supported(doc)
    sels = _selections(doc)
    excl = exclusion_selections(doc)
    main = [n for n in sels if n not in excl]
    candidates: list[dict] = []
    merged: dict = {}
    for n in main:
        merged.update(_event_for(sels[n]))
    candidates.append(merged)
    candidates += [_event_for(sels[n]) for n in main]
    positive = next((e for e in candidates if e and evaluate(doc, e)), None)
    if positive is None:
        raise UnsupportedError("no event built from the selections fires the rule")
    cases = [{"name": "Positive · built from the selections (generated)", "expect": "match", "event": positive}]

    negative = {k: BENIGN for k in positive}
    if evaluate(doc, negative):
        raise UnsupportedError("could not build a negative event")
    cases.append({"name": "Negative · same fields, benign values (generated)", "expect": "no_match", "event": negative})

    for n in sorted(excl):
        try:
            fp = {**positive, **_event_for(sels[n])}
        except UnsupportedError:
            continue
        if not evaluate(doc, fp):
            cases.append({"name": f"False positive · excluded by {n} (generated)", "kind": "false_positive",
                          "expect": "no_match", "event": fp})
    return cases


# --------------------------------------------------------------------------- import


def _matches(doc: dict, product: str | None, category: str | None, service: str | None, statuses: set[str] | None,
             text: str | None) -> bool:
    ls = doc.get("logsource") if isinstance(doc.get("logsource"), dict) else {}
    if product and str(ls.get("product", "")).lower() != product.lower():
        return False
    if category and str(ls.get("category", "")).lower() != category.lower():
        return False
    if service and str(ls.get("service", "")).lower() != service.lower():
        return False
    if statuses and str(doc.get("status", "")).lower() not in statuses:
        return False
    if text:
        hay = " ".join(str(doc.get(k, "")) for k in ("title", "description", "tags")).lower()
        if text.lower() not in hay:
            return False
    return True


def import_pack(cfg: Config, source: str, *, into: str = "sigmahq", product: str | None = None, category: str | None = None,
                service: str | None = None, statuses: tuple[str, ...] = ("stable", "test"), text: str | None = None,
                limit: int | None = None, owner: str | None = None, include_untested: bool = False,
                force: bool = False, dry_run: bool = False, folder: str = "rules") -> PackResult:
    into_rel = PurePosixPath(into)
    if into_rel.is_absolute() or ".." in into_rel.parts:
        raise PackError("--into must be a folder inside rules/")
    files = read_source(source, folder)
    if not files:
        raise PackError(f"no Sigma rules found in {source} (folder {folder}/)")
    result = PackResult()
    status_set = {s.lower() for s in statuses} if statuses else None
    for rel in sorted(files):
        if limit is not None and len(result.imported) >= limit:
            break
        text_ = files[rel]
        try:
            docs = [d for d in yaml.safe_load_all(text_) if d is not None]
        except yaml.YAMLError:
            result.skipped.append({"path": rel, "reason": "invalid YAML"})
            continue
        doc = next((d for d in docs if isinstance(d, dict) and "detection" in d), None)
        if doc is None or not _matches(doc, product, category, service, status_set, text):
            continue
        result.matched += 1
        dest = cfg.rules_dir / into_rel / rel
        cases_dest = cfg.cases_dir / into_rel / rel
        rid = (into_rel / rel).as_posix()
        if dest.exists() and not force:
            result.skipped.append({"path": rid, "reason": "already exists (use --force)"})
            continue
        try:
            cases = generate_cases(doc) if len(docs) == 1 else None
            state = "ready" if cases else "untested"
            reason = "multi-document rule" if cases is None else ""
        except UnsupportedError as exc:
            cases, state, reason = None, "untested", str(exc)
        if cases is None and not include_untested:
            result.skipped.append({"path": rid, "reason": f"no test cases could be generated ({reason})"})
            continue
        rule_text = text_
        if owner and "vitrix" not in doc and len(docs) == 1:
            rule_text = rule_text.rstrip("\n") + f"\nvitrix:\n  owner: {yaml.safe_dump(owner, default_flow_style=True).strip().removesuffix('...').strip()}\n"
        if not dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(rule_text, encoding="utf-8")
            if cases:
                cases_dest.parent.mkdir(parents=True, exist_ok=True)
                cases_dest.write_text(HEADER + yaml.safe_dump({"cases": cases}, sort_keys=False, allow_unicode=True), encoding="utf-8")
        result.imported.append({"id": rid, "title": str(doc.get("title", rel)), "level": doc.get("level"),
                                "cases": len(cases or []), "state": state, "reason": reason})
    return result
